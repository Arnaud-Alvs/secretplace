    def _smart_find(self, base_folder, requested_name, extra_exts=None):
        """Smart file finder: exact match first, then recursive search.
        
        Strategy:
        1. Try exact path: base_folder/requested_name
        2. Walk the folder tree looking for files that match the requested name
        3. If no exact match, try fuzzy: look for files containing key parts of the name
        4. For extra_exts, also try replacing .pdf with those extensions
        """
        if not os.path.isdir(base_folder):
            return None
        
        # 1. Exact match
        exact = os.path.join(base_folder, requested_name)
        if os.path.isfile(exact):
            return exact
        
        # 2. Try with extra extensions (e.g. .pptx instead of .pdf)
        if extra_exts:
            name_no_ext = os.path.splitext(requested_name)[0]
            for ext in extra_exts:
                alt = os.path.join(base_folder, name_no_ext + ext)
                if os.path.isfile(alt):
                    return alt
        
        # 3. Recursive search: exact filename match OR filename contains target as substring
        target_name = os.path.basename(requested_name)
        target_lower = target_name.lower()
        for root, dirs, files in os.walk(base_folder):
            for fn in files:
                fn_lower = fn.lower()
                if fn_lower == target_lower or target_lower in fn_lower:
                    return os.path.join(root, fn)
        
        # 4. Fuzzy: extract core title words (strip dates, extensions, "EN")
        import re
        core = os.path.splitext(target_name)[0]  # strip .pdf/.pptx
        core = re.sub(r'^\d{4}\.\d{2}\.\d{2}\s*-\s*', '', core)  # strip "2026.04.10 - " prefix
        core = re.sub(r'\d{1,2}\s+(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\w*\s+\d{4}', '', core, flags=re.IGNORECASE)  # strip "13 Apr 2026"
        core = re.sub(r'\d{1,2}\.\d{1,2}\.\d{4}', '', core)  # strip "13.04.2026"
        core = re.sub(r'\b(EN|FR)\b', '', core, flags=re.IGNORECASE)  # strip language codes
        core = re.sub(r'[-_\s]+', ' ', core).strip().lower()
        
        if len(core) > 2:
            best = None
            for root, dirs, files in os.walk(base_folder):
                for fn in files:
                    fn_lower = fn.lower()
                    if core in fn_lower and (fn_lower.endswith('.pdf') or fn_lower.endswith('.pptx') or fn_lower.endswith('.ppt') or
                        (extra_exts and any(fn_lower.endswith(e) for e in extra_exts))):
                        best = os.path.join(root, fn)
                        if ' en' in fn_lower or '_en' in fn_lower:
                            return best
            if best:
                return best
        
        # 5. Last resort: search by first significant word (3+ chars)
        words = [w for w in core.split() if len(w) >= 3 and w not in ('the', 'and', 'for')]
        if words:
            keyword = words[0]
            for root, dirs, files in os.walk(base_folder):
                for fn in files:
                    fn_lower = fn.lower()
                    if keyword in fn_lower and (fn_lower.endswith('.pdf') or fn_lower.endswith('.pptx') or fn_lower.endswith('.ppt')):
                        return os.path.join(root, fn)
        
        return None

