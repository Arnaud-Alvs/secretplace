    def _serve_publications(self):
        """Scan the 4 publication folders and return a JSON list of all PDFs
        with parsed date and title. Used by portal.html (Latest Research carousel)
        and research.html (full filterable library).
        """
        import re
        import json
        from datetime import datetime

        # ─── Filename parsers ────────────────────────────────────
        # Returns (iso_date, clean_title) or (None, None) if no match

        def parse_dotted(fn):
            # "2026.04.10 - Hermes EN.pdf"
            m = re.match(r'^(\d{4})\.(\d{2})\.(\d{2})\s*-\s*(.+?)(?:\s+EN)?\.pdf$', fn, re.IGNORECASE)
            if m:
                y, mo, d, title = m.group(1), m.group(2), m.group(3), m.group(4)
                return f"{y}-{mo}-{d}", title.strip()
            return None, None

        def parse_compact(fn):
            # "20251014-Thermo Fisher-EN.pdf" or "20251014-Title-EN.pdf"
            m = re.match(r'^(\d{4})(\d{2})(\d{2})\s*-\s*(.+?)(?:-EN|\s+EN)?\.pdf$', fn, re.IGNORECASE)
            if m:
                y, mo, d, title = m.group(1), m.group(2), m.group(3), m.group(4)
                title = re.sub(r'-EN$', '', title, flags=re.IGNORECASE).strip()
                return f"{y}-{mo}-{d}", title
            return None, None

        def parse_week_ahead(fn):
            # Usually: "{uuid}-13.04.2026 - Week ahead EN.pdf" or "13.04.2026 - Week ahead EN.pdf"
            m = re.search(r'(\d{2})\.(\d{2})\.(\d{4})', fn)
            if m:
                d, mo, y = m.group(1), m.group(2), m.group(3)
                return f"{y}-{mo}-{d}", "The Week Ahead"
            return None, None

        def parse_trend_alert(fn):
            # "Trend Alert - 13 Apr 2026.pdf"
            m = re.match(r'^Trend Alert\s*-\s*(\d{1,2})\s+(\w+)\s+(\d{4})\.pdf$', fn, re.IGNORECASE)
            if m:
                d, mon_name, y = m.group(1), m.group(2), m.group(3)
                months = {'jan':'01','feb':'02','mar':'03','apr':'04','may':'05','jun':'06',
                          'jul':'07','aug':'08','sep':'09','oct':'10','nov':'11','dec':'12',
                          'january':'01','february':'02','march':'03','april':'04',
                          'june':'06','july':'07','august':'08','september':'09',
                          'october':'10','november':'11','december':'12'}
                mo = months.get(mon_name.lower()[:3], '01')
                return f"{y}-{mo}-{d.zfill(2)}", "Trend Alert"
            return None, None

        # ─── Scan all 4 folders ──────────────────────────────────
        pubs = []
        folder_configs = [
            (FOCUS_STOCKS_FOLDER,  'Focus Stock',  '/z/focus-stocks/',  [parse_dotted, parse_compact]),
            (THEMATICS_EN_FOLDER,  'Thematic',     '/z/thematics-en/',  [parse_dotted, parse_compact]),
            (WEEK_AHEAD_FOLDER,    'Week Ahead',   '/z/week-ahead/',    [parse_week_ahead]),
            (TREND_ALERT_FOLDER,   'Trend Alert',  '/z/trend-alert/',   [parse_trend_alert]),
        ]
        for folder, doc_type, route, parsers in folder_configs:
            if not os.path.isdir(folder):
                continue
            for root, dirs, files in os.walk(folder):
                for fn in files:
                    if not fn.lower().endswith('.pdf'):
                        continue
                    # Try each parser until one matches
                    iso_date, title = None, None
                    for parser in parsers:
                        iso_date, title = parser(fn)
                        if iso_date:
                            break
                    if not iso_date:
                        continue  # Skip files we can't parse a date from
                    pubs.append({
                        'date':  iso_date,
                        'title': title,
                        'type':  doc_type,
                        'pdf':   route + fn,
                        'file':  fn,
                    })

        # Sort by date descending (most recent first)
        pubs.sort(key=lambda p: p['date'], reverse=True)

        payload = json.dumps({'count': len(pubs), 'publications': pubs}).encode('utf-8')
        self.send_response(200)
        self.send_header('Content-Type', 'application/json; charset=utf-8')
        self.send_header('Content-Length', str(len(payload)))
        self.send_header('Access-Control-Allow-Origin', '*')
        self.send_header('Cache-Control', 'no-cache')
        self.end_headers()
        self.wfile.write(payload)

